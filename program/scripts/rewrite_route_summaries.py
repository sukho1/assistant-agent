DROP = {"写文章与灵感的自然而然.md"}  # 文章已从知识库删除


def process(path):
    with open(path, encoding="utf-8") as f:
        lines = f.readlines()
    in_table = False
    changed = 0
    out = []
    for line in lines:
        s = line.rstrip("\n")
        if s.startswith("## "):
            in_table = "知识路由表" in s
            out.append(line)
            continue
        if not in_table or not s.startswith("|"):
            out.append(line)
            continue
        cells = s.split("|")
        file_idx = None
        for i, c in enumerate(cells):
            if c.strip().endswith(".md"):
                file_idx = i
                break
        if file_idx is None:
            out.append(line)
            continue
        fname = cells[file_idx].strip()
        if fname in DROP:
            changed += 1
            continue
        if fname in M:
            summary = M[fname]
            prev = cells[file_idx - 1].strip() if file_idx - 1 >= 0 else ""
            if prev.startswith("[+]"):
                summary = "[+] " + summary
            newline = "| {} | {} |\n".format(summary, fname)
            if newline != line:
                changed += 1
            out.append(newline)
        else:
            out.append(line)
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.writelines(out)
    return changed


